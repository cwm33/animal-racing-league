export const ANIMALS: Animal[] = rows.map(
  ([
    id,
    name,
    scientific,
    emoji,
    category,
    locomotion,
    mass,
    topSpeed,
    acceleration,
    sprint,
    sustainable,
    fatigue,
    color,
    description,
    biology,
  ]) => ({
    id,
    name,
    scientific,
    emoji,
    category,
    locomotion,
    color,
    description,
    biology,
    source: id === 'cheetah' ? 'cheetah' : id === 'human' ? 'human' : 'adw',
    stats: {
      mass,
      topSpeed,
      acceleration,
      sprint,
      sustainable,
      fatigue,
      delay: 0,
    },
  }),
)
export const toEntrant = (animal: Animal): Entrant => ({
  ...animal,
  stats: { ...animal.stats },
  referenceMass: animal.stats.mass,
})
export const DEFAULT_IDS = ['cheetah', 'horse', 'hippo', 'rabbit', 'tortoise']
export const defaultEntrants = () =>
  DEFAULT_IDS.map((id) => toEntrant(ANIMALS.find((a) => a.id === id)!))
